// Generates internal/icons/lucide.go from the web frontend's bundled Lucide
// icons (src/generated/lucide-icons.ts), so both apps draw the same icons
// offline. Run from mygo/: node scripts/gen-icons.mjs
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync(new URL("../../src/generated/lucide-icons.ts", import.meta.url), "utf8");
const start = src.indexOf("= {") + 2;
const json = src.slice(start, src.lastIndexOf("}") + 1);
const { icons } = JSON.parse(json);

const goName = (name) =>
  name.split("-").map((p) => p[0].toUpperCase() + p.slice(1)).join("");

let out = `// Code generated by scripts/gen-icons.mjs from src/generated/lucide-icons.ts; DO NOT EDIT.

package icons

import "github.com/egoist/mygo/ui"

func svg(body string) *ui.SVG {
	return ui.MustParseSVG([]byte(\`<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24">\` + body + \`</svg>\`))
}

// Lucide icons (ISC license, https://lucide.dev).
var (
`;
for (const name of Object.keys(icons).sort()) {
  out += `\t${goName(name)} = svg(${JSON.stringify(icons[name].body).replace(/^"|"$/g, "`").replace(/\\"/g, '"')})\n`;
}
out += ")\n";
const target = new URL("../internal/icons/lucide.go", import.meta.url);
writeFileSync(target, out);
execFileSync("gofmt", ["-w", target.pathname]);
console.log(`wrote ${Object.keys(icons).length} icons`);
