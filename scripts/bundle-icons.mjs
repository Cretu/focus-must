#!/usr/bin/env node
// Bundles every Lucide icon the app uses into src/generated/lucide-icons.ts
// so UIcon renders instantly and offline, instead of fetching icon data from
// the Iconify API at runtime (the previous behavior, which delayed first
// paint and broke icons without a network connection).
//
// Run with `npm run icons:bundle`; it also runs automatically before builds.
import {
  mkdirSync,
  readFileSync,
  readdirSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, extname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = join(root, "src");
const outFile = join(srcDir, "generated", "lucide-icons.ts");

// Icons used internally by @nuxt/ui component defaults (close buttons,
// chevrons, loaders, color-mode entries, ...). These never appear literally
// in src/, so the source scan below can't discover them.
const NUXT_UI_DEFAULT_ICONS = [
  "arrow-down",
  "arrow-left",
  "arrow-right",
  "arrow-up",
  "arrow-up-right",
  "check",
  "chevron-down",
  "chevron-left",
  "chevron-right",
  "chevron-up",
  "chevrons-left",
  "chevrons-right",
  "circle-alert",
  "circle-check",
  "circle-x",
  "copy",
  "copy-check",
  "ellipsis",
  "eye",
  "eye-off",
  "file",
  "folder",
  "folder-open",
  "grip-vertical",
  "hash",
  "info",
  "lightbulb",
  "loader-circle",
  "menu",
  "minus",
  "monitor",
  "moon",
  "panel-left-close",
  "panel-left-open",
  "plus",
  "rotate-ccw",
  "search",
  "square",
  "sun",
  "triangle-alert",
  "upload",
  "x",
];

function walk(dir, files = []) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    const stats = statSync(full);
    if (stats.isDirectory()) {
      if (entry === "generated") continue;
      walk(full, files);
    } else if ([".vue", ".ts"].includes(extname(entry))) {
      files.push(full);
    }
  }
  return files;
}

const used = new Set(NUXT_UI_DEFAULT_ICONS);
for (const file of [...walk(srcDir), join(root, "index.html")]) {
  const text = readFileSync(file, "utf8");
  for (const match of text.matchAll(/i-lucide-([a-z0-9]+(?:-[a-z0-9]+)*)/g)) {
    used.add(match[1]);
  }
}

const lucide = JSON.parse(
  readFileSync(
    join(root, "node_modules", "@iconify-json", "lucide", "icons.json"),
    "utf8",
  ),
);

const icons = {};
const aliases = {};
const missing = [];

for (const name of [...used].sort()) {
  if (lucide.icons[name]) {
    icons[name] = lucide.icons[name];
    continue;
  }
  const alias = lucide.aliases?.[name];
  if (alias && lucide.icons[alias.parent]) {
    aliases[name] = alias;
    icons[alias.parent] = lucide.icons[alias.parent];
    continue;
  }
  missing.push(name);
}

if (missing.length > 0) {
  console.error(
    `bundle-icons: unknown Lucide icon name(s): ${missing.join(", ")}`,
  );
  process.exit(1);
}

const bundle = {
  prefix: "lucide",
  icons,
  width: lucide.width,
  height: lucide.height,
};
if (Object.keys(aliases).length > 0) {
  bundle.aliases = aliases;
}

const banner =
  "// Generated by scripts/bundle-icons.mjs — do not edit by hand.\n" +
  "// Regenerate with `npm run icons:bundle` after adding or removing icons.\n";

mkdirSync(join(srcDir, "generated"), { recursive: true });
writeFileSync(
  outFile,
  `${banner}import type { IconifyJSON } from "@iconify/vue";\n\nconst lucideIcons: IconifyJSON = ${JSON.stringify(bundle, null, 2)};\n\nexport default lucideIcons;\n`,
);

console.log(
  `bundle-icons: wrote ${Object.keys(icons).length} icons` +
    (Object.keys(aliases).length > 0
      ? ` (+${Object.keys(aliases).length} aliases)`
      : "") +
    ` to src/generated/lucide-icons.ts`,
);
